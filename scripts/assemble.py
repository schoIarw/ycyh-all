#!/usr/bin/env python3
"""Build the single-file installer. --check detects framework/resource drift."""
from pathlib import Path
import sys
root=Path(__file__).resolve().parents[1]
parts=[root/'scripts/framework/common.sh',root/'scripts/components/elasticsearch/install.sh']
body='#!/usr/bin/env bash\n# Generated by scripts/assemble.py; edit framework/adapter sources.\n'+'\n'.join(p.read_text() for p in parts)+'\nframework_main\n'
target=root/'clustermgr/src/main/resources/scripts/install-es.sh'
if '--check' in sys.argv:
    if not target.exists() or target.read_text()!=body:raise SystemExit('Installer is stale: run python3 scripts/assemble.py')
else:
    target.parent.mkdir(parents=True,exist_ok=True);target.write_text(body)
