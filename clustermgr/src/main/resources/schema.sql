CREATE TABLE IF NOT EXISTS clusters (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(64) NOT NULL UNIQUE, package_path VARCHAR(1000) NOT NULL,
 sha256 VARCHAR(64) NOT NULL, application_id VARCHAR(36), created_at VARCHAR(40) NOT NULL
);
CREATE TABLE IF NOT EXISTS deploy_tasks (
 id VARCHAR(36) PRIMARY KEY, cluster_id VARCHAR(36) NOT NULL, host_ip VARCHAR(45) NOT NULL,
 username VARCHAR(64) NOT NULL, script_uuid VARCHAR(36), token_hash VARCHAR(64) NOT NULL,
 status VARCHAR(24) NOT NULL, phase VARCHAR(24) NOT NULL, last_seq INTEGER NOT NULL DEFAULT 0,
 created_at VARCHAR(40) NOT NULL, finished_at VARCHAR(40), detail VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS deploy_events (
 id VARCHAR(64) PRIMARY KEY, task_id VARCHAR(36) NOT NULL, seq INTEGER NOT NULL,
 phase VARCHAR(24) NOT NULL, message TEXT NOT NULL, created_at VARCHAR(40) NOT NULL
);
